/// A kernel snap's boot assets, located per the payload convention in
/// [`locate_kernel_payload`].
#[derive(Debug)]
pub(crate) struct KernelPayload {
    pub(crate) kernel: PathBuf,
    pub(crate) initrd: PathBuf,
    pub(crate) version: String,
    /// `true` when the kernel and initrd came from a prebuilt Canonical
    /// `kernel.efi` (the Ubuntu Core `pc-kernel` layout, #70) rather than
    /// raw `vmlinuz`/`initrd` files. A prebuilt UKI carries Canonical's
    /// snap-bootstrap initramfs, which mounts a writable `ubuntu-data` and
    /// never honors shuttle's verity cmdline — the build replaces its initrd
    /// with shuttle's native one (issue #75). `false` for the raw path.
    pub(crate) prebuilt_uki: bool,
    /// `.sbat` (SBAT — Secure Boot Advanced Targeting) revocation policy
    /// carried VERBATIM from the prebuilt `kernel.efi` into the rebuilt UKI
    /// via `ukify --sbat` (issue #73). Under an SBAT-enforcing shim, a UKI
    /// whose policy lines are dropped is measured against a revocation
    /// lineage that no longer describes it, so the upstream section is
    /// carried as-is or the build fails closed — it is never invented.
    /// `None` for the raw path: there is no upstream UKI, and the rebuilt
    /// UKI keeps whatever `.sbat` the sd-stub itself carries.
    pub(crate) sbat: Option<PathBuf>,
    /// Keeps UKI-extracted boot assets alive when the payload came from a
    /// prebuilt `kernel.efi` rather than raw files (issue #70). `None` for
    /// the raw path, where the files live in the extracted snap tree.
    pub(crate) _scratch: Option<tempfile::TempDir>,
}

impl KernelPayload {
    /// A payload backed by files already on disk (the raw convention path).
    pub(crate) fn raw(kernel: PathBuf, initrd: PathBuf, version: String) -> KernelPayload {
        KernelPayload {
            kernel,
            initrd,
            version,
            prebuilt_uki: false,
            sbat: None,
            _scratch: None,
        }
    }
}

/// Boot facts captured during UKI assembly (ADR-0011 step (a)) and threaded
/// into the build manifest — the image records what will actually boot,
/// not just what was packed.
pub(crate) struct UkiFacts {
    pub(crate) kernel_version: String,
    pub(crate) cmdline: String,
    pub(crate) uki_filename: String,
    pub(crate) esp_partuuid: Option<String>,
    /// dm-verity root hash embedded in the cmdline (ADR-0011 step (c));
    /// None for images that boot without verity.
    pub(crate) roothash: Option<String>,
}

/// GPT PARTUUID emitted when the real root PARTUUID could not be resolved.
/// Documented placeholder strategy: the nil GUID makes the failure loud —
/// nothing can mount a partition that does not exist, so the image never
/// silently boots from the wrong volume. In practice the real PARTUUID is
/// captured: parted assigns GPT GUIDs at mkpart time and `sfdisk -J` reads
/// them back from the finished table before the UKI is built.
pub(crate) const NIL_PARTUUID: &str = "00000000-0000-0000-0000-000000000000";

/// Standard locations of the systemd sd-stub for x86_64 — all under the
/// sandbox bind roots ([`crate::snap::SANDBOX_RO_ROOTS`]).
pub(crate) const EFI_STUB_CANDIDATES: [&str; 3] = [
    "/usr/lib/systemd/boot/efi/linuxx64.efi.stub",
    "/usr/local/lib/systemd/boot/efi/linuxx64.efi.stub",
    "/run/current-system/sw/lib/systemd/boot/efi/linuxx64.efi.stub",
];

/// Kernel-snap payload convention (ADR-0011 step (a), extended by #70) —
/// defined explicitly because no convention existed: pkgs/*-kernel.lua snaps
/// are source-type with no packed kernel. After the snap is extracted, boot
/// assets are read from the payload in this fixed order, with the version
/// taken from the merged rootfs module tree (`lib/modules/<version>` — the
/// only kernel payload path this repo already merges):
///
///   kernel: boot/vmlinuz-<ver> → boot/vmlinuz → vmlinuz-<ver> → vmlinuz
///   initrd: boot/initrd.img-<ver> → boot/initrd.img → initrd.img → initrd
///
/// Raw kernel binaries are first choice. When no raw pair is present, the
/// real Ubuntu Core `pc-kernel` layout (#70) is used instead: a prebuilt
/// [`KERNEL_EFI_NAME`] UKI at the snap root is split with `objcopy` into its
/// `.linux`/`.initrd` PE sections (and its `.sbat` revocation policy, #73)
/// and shuttle re-assembles its OWN UKI from them — the per-image cmdline
/// (root=PARTUUID, dm-verity roothash) must live INSIDE the signed UKI, and
/// systemd-stub ignores LoadOptions under Secure Boot when a UKI carries an
/// embedded cmdline. A snapd-style `kernel.img` squashfs payload is not
/// unpacked (that is gadget-stage behavior).
pub(crate) fn locate_kernel_payload(
    runner: &dyn CommandRunner,
    objcopy: Option<&Path>,
    scratch: &Path,
    kernel_dir: &Path,
    root: &Path,
) -> miette::Result<KernelPayload> {
    let version = discover_kernel_version(root)?;
    if let Some(payload) = locate_raw_payload(kernel_dir, version.clone())? {
        return Ok(payload);
    }
    locate_uki_payload(runner, objcopy, scratch, kernel_dir, version)
}

/// The raw `vmlinuz`/`initrd` convention ([`locate_kernel_payload`]). `None`
/// when either half is absent — the caller then falls back to the prebuilt
/// UKI (#70).
fn locate_raw_payload(kernel_dir: &Path, version: String) -> miette::Result<Option<KernelPayload>> {
    let kernel = first_existing([
        kernel_dir.join("boot").join(format!("vmlinuz-{version}")),
        kernel_dir.join("boot").join("vmlinuz"),
        kernel_dir.join(format!("vmlinuz-{version}")),
        kernel_dir.join("vmlinuz"),
    ]);
    let initrd = first_existing([
        kernel_dir
            .join("boot")
            .join(format!("initrd.img-{version}")),
        kernel_dir.join("boot").join("initrd.img"),
        kernel_dir.join("initrd.img"),
        kernel_dir.join("initrd"),
    ]);
    match (kernel, initrd) {
        (Some(kernel), Some(initrd)) => Ok(Some(KernelPayload::raw(kernel, initrd, version))),
        (None, None) => Ok(None),
        (None, Some(_)) => Err(miette::miette!(
            "payload has no kernel image (searched boot/vmlinuz-{version}, boot/vmlinuz, \
             vmlinuz-{version}, vmlinuz)"
        )),
        (Some(_), None) => Err(miette::miette!(
            "payload has no initrd (searched boot/initrd.img-{version}, boot/initrd.img, \
             initrd.img, initrd)"
        )),
    }
}

/// The prebuilt-UKI fallback for the real Ubuntu Core `pc-kernel` layout
/// (#70): `kernel.efi` at the snap root, split into `.linux`/`.initrd`
/// PE sections via `objcopy` — plus its `.sbat` revocation policy, carried
/// verbatim into the rebuilt UKI (#73). Both payload halves must be found
/// and extracted, the `.sbat` must be present and well-formed (it is the
/// revocation lineage under an SBAT-enforcing shim), and the extracted
/// bzImage banner must agree with the discovered module version — anything
/// less fails closed with the exact cause.
fn locate_uki_payload(
    runner: &dyn CommandRunner,
    objcopy: Option<&Path>,
    scratch: &Path,
    kernel_dir: &Path,
    version: String,
) -> miette::Result<KernelPayload> {
    let uki = first_existing([kernel_dir.join(KERNEL_EFI_NAME)]).ok_or_else(|| {
        miette::miette!(
            "payload has no kernel image (searched boot/vmlinuz-{version}, boot/vmlinuz, \
             vmlinuz-{version}, vmlinuz) and no prebuilt {KERNEL_EFI_NAME} at the snap root"
        )
    })?;
    let Some(objcopy) = objcopy else {
        return Err(miette::miette!(
            "objcopy not found on PATH — splitting {KERNEL_EFI_NAME} into its .linux/.initrd \
             sections needs binutils, so refusing to build a disk image that cannot boot. Run \
             'shuttle doctor' and install binutils"
        ));
    };
    let dir = scratch.join("uki-sections");
    std::fs::create_dir_all(&dir).into_diagnostic()?;
    let kernel = dir.join("vmlinuz");
    let initrd = dir.join("initrd");
    for (section, out) in [(".linux", &kernel), (".initrd", &initrd)] {
        extract_pe_section(runner, objcopy, &uki, section, out)?;
    }
    // #73: carry the upstream `.sbat` verbatim. Revocation metadata the
    // rebuilt UKI drops would let a kernel boot past revocations issued
    // against the original, so a missing or malformed section is a hard
    // failure, never a warning.
    let sbat = dir.join("sbat");
    extract_pe_section(runner, objcopy, &uki, ".sbat", &sbat)?;
    let sbat = validate_sbat_payload(&sbat, &uki)?;
    verify_bzimage_version(&kernel, &version)?;
    Ok(KernelPayload {
        kernel,
        initrd,
        version,
        prebuilt_uki: true,
        sbat: Some(sbat),
        _scratch: None,
    })
}

/// Validate the extracted `.sbat` payload (#73) and normalize it in place
/// for the `ukify --sbat=@path` hand-off.
///
/// `objcopy -O binary --only-section` reports an ABSENT section as exit 0
/// with a ZERO-BYTE output file (measured: binutils 2.46), so absence is
/// detected here, not by the exit code. Empty output means the source UKI
/// carries no `.sbat` at all: its revocation lineage cannot be carried, and
/// a rebuilt UKI without it would boot past revocations targeting the
/// original — refused.
///
/// Non-empty payloads are trimmed of trailing NUL section padding, must
/// decode as UTF-8, and must start with the `sbat,` version line. That last
/// check mirrors `ukify`'s own merge step, which SKIPS a `--sbat` input that
/// does not start with `sbat,` — printing a warning while exiting 0 (read
/// from ukify's merge_sbat). Without the pre-check, a malformed upstream
/// section would be dropped from the rebuilt UKI with a green build. The
/// trimmed bytes are written back so the file handed to ukify is exactly
/// the validated policy; the policy itself is never rewritten.
fn validate_sbat_payload(sbat: &Path, uki: &Path) -> miette::Result<PathBuf> {
    let bytes = std::fs::read(sbat)
        .into_diagnostic()
        .wrap_err_with(|| format!("reading extracted .sbat from {}", uki.display()))?;
    if bytes.is_empty() {
        return Err(miette::miette!(
            "{KERNEL_EFI_NAME} carries no .sbat section — its SBAT Secure Boot revocation \
             lineage cannot be carried into the rebuilt UKI (#73), so refusing to build a \
             disk image whose boot chain cannot be revoked by shim's SBAT policy"
        ));
    }
    let trimmed = match bytes.iter().rposition(|&b| b != 0) {
        Some(last) => &bytes[..=last],
        None => &bytes[..],
    };
    let text = std::str::from_utf8(trimmed).map_err(|e| {
        miette::miette!(
            "{KERNEL_EFI_NAME}'s .sbat section is not valid UTF-8 ({e}) — a policy that \
             cannot be read cannot be carried (#73); refusing to build"
        )
    })?;
    if !text.lines().next().is_some_and(|l| l.starts_with("sbat,")) {
        return Err(miette::miette!(
            "{KERNEL_EFI_NAME}'s .sbat section does not start with an 'sbat,' version line — \
             ukify would silently DROP it from the rebuilt UKI (#73); refusing to build with \
             a revocation policy that would not be carried. First line: {:?}",
            text.lines().next().unwrap_or("")
        ));
    }
    std::fs::write(sbat, trimmed).into_diagnostic()?;
    Ok(sbat.to_path_buf())
}

/// `objcopy -O binary --only-section=<section> <uki> <out>` through the
/// injected runner, failing closed on a nonzero exit or a missing output.
fn extract_pe_section(
    runner: &dyn CommandRunner,
    objcopy: &Path,
    uki: &Path,
    section: &str,
    out: &Path,
) -> miette::Result<()> {
    let argv = vec![
        objcopy.to_string_lossy().into_owned(),
        "-O".to_string(),
        "binary".to_string(),
        format!("--only-section={section}"),
        uki.to_string_lossy().into_owned(),
        out.to_string_lossy().into_owned(),
    ];
    let result = runner.run(&argv).map_err(|e| {
        miette::miette!(
            "failed to run objcopy to extract {section} from {}: {e}",
            uki.display()
        )
    })?;
    if result.code != 0 {
        return Err(miette::miette!(
            "objcopy failed to extract {section} from {} (exit {}): {}. The prebuilt UKI \
             does not carry the section shuttle needs to assemble its own UKI",
            uki.display(),
            result.code,
            result.stderr.trim()
        ));
    }
    if !out.is_file() {
        return Err(miette::miette!(
            "objcopy reported success but {section} of {} produced no file at {}",
            uki.display(),
            out.display()
        ));
    }
    Ok(())
}

/// Build-time hard gate (ADR-0024 §1): the resolved kernel's initrd must
/// carry every boot-chain module its config builds as a module
/// (`virtio_blk`, `virtio_pci`, `dm_mod`, `dm-verity`, `ext4` on the
/// audited kernels). A kernel whose initrd cannot see its own disk is a
/// brick, so this FAILS CLOSED — an unavailable config, an unreadable or
/// unrecognized initrd, and a missing module are all hard errors naming
/// the exact cause. The required set is derived from the kernel config
/// ([`doctor::inspect_initrd_modules`]), never hardcoded.
pub(crate) fn audit_initrd_modules(
    runner: &dyn CommandRunner,
    payload_dir: &Path,
    payload: &KernelPayload,
) -> miette::Result<()> {
    use crate::doctor::InitrdModuleAudit;
    match doctor::inspect_initrd_modules(runner, payload_dir, &payload.version, &payload.initrd) {
        InitrdModuleAudit::Satisfied(modules) if modules.is_empty() => {
            eprintln!(
                "  ✓ initrd module audit: kernel {} builds the boot chain in — no \
                 initrd modules required",
                payload.version
            );
            Ok(())
        }
        InitrdModuleAudit::Satisfied(modules) => {
            eprintln!(
                "  ✓ initrd module audit: kernel {} initrd carries {}",
                payload.version,
                modules.join(", ")
            );
            Ok(())
        }
        InitrdModuleAudit::Missing { config, missing } => Err(miette::miette!(
            "kernel {} initrd is missing boot-chain module(s): {} (required by {}); \
             the kernel cannot see its own disk at boot — refusing to build a disk \
             image that cannot boot (ADR-0024 §1). A stock Ubuntu Core kernel payload \
             ships Canonical's snap-bootstrap initramfs, which mounts a writable \
             ubuntu-data and never verifies a shuttle verity root, so a complete \
             module set would not make it honor this image's cmdline either. \
             Legitimate exits: a kernel snap in the raw vmlinuz/initrd convention \
             whose initrd carries the boot-chain modules (or one that builds them in), \
             or shuttle building its own initramfs (issue #75)",
            payload.version,
            missing.join(", "),
            config.display()
        )),
        InitrdModuleAudit::NoConfig => Err(miette::miette!(
            "no kernel config found for {} under {} — cannot derive the required \
             boot-chain modules, and a kernel whose initrd cannot be verified must \
             not ship; refusing to build a disk image that cannot boot (ADR-0024 §1)",
            payload.version,
            payload_dir.display()
        )),
        InitrdModuleAudit::Unreadable(reason) => Err(miette::miette!(
            "kernel {} initrd {} could not be read: {reason}; refusing to build a \
             disk image that cannot boot (ADR-0024 §1)",
            payload.version,
            payload.initrd.display()
        )),
    }
}

/// First path in `candidates` that exists as a file.
pub(crate) fn first_existing(candidates: impl IntoIterator<Item = PathBuf>) -> Option<PathBuf> {
    candidates.into_iter().find(|p| p.is_file())
}

/// Kernel version from the merged rootfs module tree: the single directory
/// under `lib/modules/`. Ambiguous or absent trees fail closed.
pub(crate) fn discover_kernel_version(root: &Path) -> miette::Result<String> {
    let modules_dir = root.join("lib").join("modules");
    let mut versions: Vec<String> = std::fs::read_dir(&modules_dir)
        .into_diagnostic()
        .wrap_err_with(|| format!("reading {}", modules_dir.display()))?
        .flatten()
        .filter(|e| e.path().is_dir())
        .filter_map(|e| e.file_name().to_str().map(str::to_string))
        .collect();
    versions.sort();
    match versions.as_slice() {
        [one] => Ok(one.clone()),
        [] => Err(miette::miette!(
            "no kernel module tree (lib/modules/<version>) in the merged rootfs — \
             the kernel snap carries no recognizable version"
        )),
        many => Err(miette::miette!(
            "ambiguous kernel module trees {many:?} in the merged rootfs — a kernel \
             snap must carry exactly one lib/modules/<version>"
        )),
    }
}

