/// Length of the bzImage probe window. The setup header (and, for builds
/// that keep the string uncompressed, the banner) sits in the first pages.
const BZIMAGE_BANNER_WINDOW: usize = 64 * 1024;

/// Read the version a bzImage was built for, from its setup header.
///
/// `HdrS` lives at offset 0x202 and the u16 at 0x20E is the offset, relative
/// to the 0x200 base, of the NUL-terminated version string. That string is
/// part of the setup header, so it is readable even when the kernel payload
/// itself is compressed (the real `pc-kernel` `.linux` is zstd-compressed,
/// which is why scanning the image for the banner text finds nothing).
/// Falls back to scanning for the banner, then returns `None`.
pub(crate) fn bzimage_banner_version(image: &[u8]) -> Option<String> {
    if let Some(version) = bzimage_header_version(image) {
        return Some(version);
    }
    let window = image.get(..image.len().min(BZIMAGE_BANNER_WINDOW))?;
    let text = String::from_utf8_lossy(window);
    let rest = text.split("Linux version ").nth(1)?;
    let version = rest.split_whitespace().next()?;
    (!version.is_empty()).then(|| version.to_string())
}

/// The setup-header (`HdrS`) version string, or `None` when the header is
/// absent or the offset is out of range.
fn bzimage_header_version(image: &[u8]) -> Option<String> {
    const SETUP_BASE: usize = 0x200;
    if image.len() < SETUP_BASE + 0x210 || &image[SETUP_BASE + 2..SETUP_BASE + 6] != b"HdrS" {
        return None;
    }
    let rel = u16::from_le_bytes([
        *image.get(SETUP_BASE + 0x0e)?,
        *image.get(SETUP_BASE + 0x0f)?,
    ]) as usize;
    let start = SETUP_BASE.checked_add(rel)?;
    let tail = image.get(start..)?;
    let end = tail.iter().position(|b| *b == 0)?;
    let version = String::from_utf8_lossy(&tail[..end]).trim().to_string();
    (!version.is_empty()).then_some(version)
}

/// Cross-check the extracted bzImage's version against the ABI version the
/// `modules/<ver>` tree names (#70). The module directory is authoritative —
/// `uname -r` reports it — so the check is a skew guard, not a validity
/// proof: it reports a disagreement, and warns (rather than failing) when the
/// payload carries no readable version at all, because the payload may be
/// compressed in a way that hides the string. Only an explicit, differing
/// version fails the build.
fn verify_bzimage_version(image: &Path, expected: &str) -> miette::Result<()> {
    let bytes = std::fs::read(image)
        .into_diagnostic()
        .wrap_err_with(|| format!("reading extracted kernel {}", image.display()))?;
    let Some(actual) = bzimage_banner_version(&bytes) else {
        eprintln!(
            "  ⚠ extracted kernel {} carries no readable version banner — cannot \
             cross-check it against modules/{expected} (the module tree stays \
             authoritative)",
            image.display()
        );
        return Ok(());
    };
    if actual != expected && !actual.starts_with(expected) {
        return Err(miette::miette!(
            "kernel version mismatch: {KERNEL_EFI_NAME}'s .linux section reports '{actual}' but \
             the module tree is modules/{expected} — the snap's UKI and modules disagree, so \
             refusing to build a disk image that cannot boot"
        ));
    }
    eprintln!(
        "  ✓ kernel {}: {KERNEL_EFI_NAME} .linux section matches modules/{expected}",
        image.display()
    );
    Ok(())
}

/// Locate the systemd sd-stub the UKI is built on.
pub(crate) fn find_efi_stub() -> Option<PathBuf> {
    for candidate in EFI_STUB_CANDIDATES {
        let path = Path::new(candidate);
        if path.is_file() {
            return Some(path.to_path_buf());
        }
    }
    None
}

/// Filename of the UKI on the ESP (systemd-boot auto-discovers Type-2 UKIs
/// in EFI/Linux/, and the loader.conf default pattern keys off this name).
pub(crate) fn uki_filename(image: &ImageDeclaration) -> String {
    format!("{}_{}.efi", image.name, image.version)
}

/// Compose the UKI kernel command line from parts — never one opaque
/// string. A UKI's `.cmdline` section is immutable once built, and dm-verity
/// boot (ADR-0011 step (c)) appends `roothash=` plus the explicit verity
/// device arguments ([`verity_trailing`]) and Secure Boot will later sign
/// the result, so composition stays programmatic: declared kernel params
/// first (user intent), then the `root=` argument derived from the target
/// root partition, then the trailing verity args (appended last).
pub(crate) fn compose_cmdline(
    params: &[String],
    root_partuuid: Option<&str>,
    trailing: &[String],
) -> String {
    let mut args: Vec<String> = params.to_vec();
    args.push(match root_partuuid {
        Some(uuid) => format!("root=PARTUUID={uuid}"),
        None => format!("root=PARTUUID={NIL_PARTUUID}"),
    });
    args.extend(trailing.iter().cloned());
    args.join(" ")
}

/// Deterministic os-release for the UKI: no timestamps, no host facts —
/// the same definition always yields byte-identical boot assets.
///
/// `IMAGE_VERSION` is set deliberately: systemd-sysupdate's `%A` transfer
/// specifier resolves to the `IMAGE_VERSION=` field (NOT `VERSION_ID=` —
/// that is `%w`), and the generated transfers carry
/// `ProtectVersion=%A` (ADR-0011 step (d)). Without this field `%A`
/// expands to the empty string and `ProtectVersion=` protects nothing.
pub(crate) fn write_uki_os_release(
    stage_dir: &Path,
    image: &ImageDeclaration,
) -> miette::Result<PathBuf> {
    let path = stage_dir.join("os-release");
    std::fs::write(
        &path,
        format!(
            "ID=shuttle\nNAME=\"{name}\"\nVERSION_ID={version}\nIMAGE_VERSION={version}\nPRETTY_NAME=\"shuttle {name} {version}\"\n",
            name = image.name,
            version = image.version,
        ),
    )
    .into_diagnostic()?;
    Ok(path)
}

/// Build one UKI with the real `ukify` CLI. `ukify` and `stub` are
/// injected so the fail-closed behavior is testable on hosts without
/// systemd's tools; [`build_uki`] resolves them from the host. `sbat` is
/// the upstream `.sbat` payload to carry verbatim (#73) — `None` leaves the
/// sd-stub's own policy in place, never an invented one.
#[allow(clippy::too_many_arguments)]
pub(crate) fn build_uki_with(
    runner: &dyn CommandRunner,
    ukify: Option<&Path>,
    stub: Option<&Path>,
    kernel: &Path,
    initrd: &Path,
    cmdline: &str,
    os_release: &Path,
    sbat: Option<&Path>,
    output: &Path,
) -> miette::Result<()> {
    let Some(ukify) = ukify else {
        return Err(miette::miette!(
            "ukify not found on PATH — a kernel disk image cannot boot without a UKI, \
             so refusing to produce an unbootable image. Run 'shuttle doctor' and \
             install ukify (systemd >= 254; e.g. apt install systemd-ukify or add \
             systemd to devbox.json packages)"
        ));
    };
    let Some(stub) = stub else {
        return Err(miette::miette!(
            "systemd sd-stub (linuxx64.efi.stub) not found — the UKI cannot be assembled \
             without it. Run 'shuttle doctor'; checked locations: {}",
            EFI_STUB_CANDIDATES.join(", ")
        ));
    };
    let mut argv = vec![
        ukify.to_string_lossy().into_owned(),
        "build".to_string(),
        format!("--linux={}", kernel.display()),
        format!("--initrd={}", initrd.display()),
        format!("--cmdline={cmdline}"),
        format!("--os-release=@{}", os_release.display()),
        format!("--stub={}", stub.display()),
    ];
    // `@PATH`, not inline text: the extracted bytes pass through byte-identical
    // (ukify reads the file as text and merges its lines with the stub's own
    // policy — nothing is truncated or replaced). Section carry itself never
    // touches `objcopy --update-section`, which silently truncates the input
    // to the existing section size; the UKI is assembled fresh on the stub.
    if let Some(sbat) = sbat {
        argv.push(format!("--sbat=@{}", sbat.display()));
    }
    argv.push(format!("--output={}", output.display()));
    let out = runner
        .run(&argv)
        .map_err(|e| miette::miette!("failed to run ukify: {e}"))?;
    if out.code != 0 || !output.is_file() {
        return Err(miette::miette!(
            "ukify failed to build the UKI — the disk image would not boot; \
             refusing to emit it"
        ));
    }
    Ok(())
}

/// Build the UKI with host-resolved ukify and sd-stub (fail-closed when
/// either is absent).
pub(crate) fn build_uki(
    runner: &dyn CommandRunner,
    kernel: &Path,
    initrd: &Path,
    cmdline: &str,
    os_release: &Path,
    sbat: Option<&Path>,
    output: &Path,
) -> miette::Result<()> {
    build_uki_with(
        runner,
        find_ukify().as_deref(),
        find_efi_stub().as_deref(),
        kernel,
        initrd,
        cmdline,
        os_release,
        sbat,
        output,
    )
}

/// Compose the cmdline, build the UKI into `stage_dir`, and capture the
/// boot facts for the manifest. The facts are `None` only for kernel-free
/// images (nothing to boot, no UKI needed); the staged UKI path is empty
/// then and never used. `verity` carries the ADR-0011 step (c) format-time
/// roothash — Some exactly when the build verity-formatted the root
/// partition (kernel images).
pub(crate) fn assemble_uki(
    runner: &dyn CommandRunner,
    image: &ImageDeclaration,
    payload: Option<&KernelPayload>,
    extents: &[PartitionExtent],
    layout: &DiskLayout,
    stage_dir: &Path,
    verity: Option<&VerityBootArgs>,
) -> miette::Result<(Option<UkiFacts>, PathBuf)> {
    let Some(entry) = image.kernel.as_ref() else {
        return Ok((None, PathBuf::new()));
    };
    let Some(payload) = payload else {
        return Err(miette::miette!(
            "kernel snap '{}' declared but its boot payload was not extracted — \
             refusing to build a disk image that cannot boot",
            entry.snap.name
        ));
    };
    let root_idx = root_partition_index(layout)?;

    // GPT PARTUUIDs exist from parted mkpart time and are read back from
    // the finished table (`sfdisk -J`) before anything is formatted. ESP
    // is partition 1 (extent index 0).
    let root_partuuid = extents[root_idx].partuuid.clone();
    let esp_partuuid = extents[0].partuuid.clone();
    if root_partuuid.is_none() {
        eprintln!(
            "  ⚠ root PARTUUID unresolvable — cmdline carries the documented \
             nil-GUID placeholder (see compose_cmdline)"
        );
    }

    let trailing: Vec<String> = verity
        .map(|v| {
            verity_trailing(
                &v.roothash,
                root_partuuid.as_deref(),
                v.hash_partuuid.as_deref(),
            )
        })
        .unwrap_or_default();
    let cmdline = compose_cmdline(&entry.params, root_partuuid.as_deref(), &trailing);
    let filename = uki_filename(image);
    let uki_stage = stage_dir.join(&filename);
    let os_release = write_uki_os_release(stage_dir, image)?;
    build_uki(
        runner,
        &payload.kernel,
        &payload.initrd,
        &cmdline,
        &os_release,
        payload.sbat.as_deref(),
        &uki_stage,
    )?;
    eprintln!("  ✓ UKI built: {filename}");
    if let Some(sbat) = payload.sbat.as_deref() {
        let lines = std::fs::read_to_string(sbat)
            .map(|t| t.lines().count().saturating_sub(1))
            .unwrap_or(0);
        eprintln!(
            "  ✓ SBAT carried from {} ({lines} revocation component line(s), #73)",
            KERNEL_EFI_NAME
        );
    }

    Ok((
        Some(UkiFacts {
            kernel_version: payload.version.clone(),
            cmdline,
            uki_filename: filename,
            esp_partuuid,
            roothash: verity.map(|v| v.roothash.clone()),
        }),
        uki_stage,
    ))
}

/// systemd-boot loader configuration at the ESP root. Type-2 UKIs in
/// EFI/Linux/*.efi are auto-discovered — no per-entry loader file needed —
/// but the timeout and default pattern live here.
pub(crate) fn loader_conf(image: &ImageDeclaration) -> String {
    let timeout = image.bootloader.as_ref().map(|b| b.timeout).unwrap_or(3);
    // `default` is a glob: any UKI built for this image name matches,
    // regardless of version.
    format!(
        "# Generated by shuttle — do not edit.\ntimeout {timeout}\ndefault {}_*\n",
        image.name
    )
}
